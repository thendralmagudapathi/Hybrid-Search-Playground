const LONG_HANDBOOK = `Platform engineering handbook (overview chapter). This chapter is a long tour of how our platform team works, so it touches many topics briefly instead of going deep on any one of them.
On-call: each engineer joins the rotation after their first quarter. The primary responder acknowledges a page within five minutes, opens an incident channel, and writes a short summary for the next shift. Secondary responders help with communication and with rolling changes back when needed.
Deployments: services ship through the same pipeline. Builds are reproducible, images are signed, and every change goes to a canary group before the rest of the fleet. If the canary shows higher error rates the pipeline stops on its own.
Observability: we collect logs, metrics and traces for every service. Dashboards show request volume, error rate and latency for each endpoint. We review latency every week and we set alerts on latency budgets per team, but the handbook does not cover how to choose thresholds; see the monitoring guide for that.
Databases: teams own their schemas. Migrations must be backwards compatible so that old and new code can run side by side during a deploy. Large backfills run in small batches at night.
Caching: shared caches are managed by the platform team. Teams request a namespace and agree on key naming. Entries should always have a time to live.
Security: secrets live in the vault, never in source control. Access is reviewed every quarter, and production access requires a second approver.
Cost: every service has a monthly budget. Idle environments are shut down automatically on weekends. Storage older than a year moves to cheaper tiers.
Documentation: each service keeps a short readme with an owner, a runbook link, and the steps to run it locally. Architecture decisions are recorded in a decision log so that new joiners understand why things are the way they are.
Learning: engineers get time each month for training, reading groups and internal talks. New joiners pair with a buddy for their first month.`;

